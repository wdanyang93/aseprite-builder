def labels(kind, shape):
    """Label image on the neutral: index into NAMES + 1 (0 = unlabelled)."""
    lab = np.zeros(shape, np.uint8)
    for name, poly in reversed(POLY[kind]):
        cv2.fillPoly(lab, [np.array(poly, np.int32)], NAMES.index(name) + 1)
    return lab


def carry(x, mp, nearest=False):
    """neutral-space array -> frame via a ground-truth map (frame px -> neutral px coordinates)."""
    return cv2.remap(x, mp[..., 0], mp[..., 1], cv2.INTER_NEAREST if nearest else cv2.INTER_LINEAR,
                     borderMode=cv2.BORDER_CONSTANT, borderValue=0)
